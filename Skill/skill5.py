import os
import json
import random
import io
import requests
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.patches as patches

from PIL import Image
from google.colab import files
from ultralytics import YOLO

print("All libraries imported successfully!")

print("Creating sample Indian Traffic Dataset...")

os.makedirs("sample_traffic/images", exist_ok=True)

classes = [
    "car",
    "truck",
    "bus",
    "auto-rickshaw",
    "two-wheeler",
    "person",
    "traffic-light"
]

class_to_id = {
    name: i + 1
    for i, name in enumerate(classes)
}

coco_data = {
    "info": {
        "description": "Synthetic Indian Traffic Dataset",
        "version": "1.0"
    },
    "categories": [
        {
            "id": cid,
            "name": name,
            "supercategory": "vehicle"
        }
        for name, cid in class_to_id.items()
    ],
    "images": [],
    "annotations": []
}

ann_id = 1

for img_id in range(1, 16):

    img = np.random.randint(
        0, 255, (640, 640, 3), dtype=np.uint8
    )

    img_path = f"sample_traffic/images/img_{img_id:03d}.jpg"

    Image.fromarray(img).save(img_path)

    coco_data["images"].append({
        "id": img_id,
        "file_name": f"img_{img_id:03d}.jpg",
        "width": 640,
        "height": 640
    })

    for _ in range(random.randint(2, 5)):

        cat = random.choice(list(class_to_id.values()))

        w = random.randint(30, 250)
        h = random.randint(30, 250)

        x = random.randint(0, 640 - w)
        y = random.randint(0, 640 - h)

        coco_data["annotations"].append({
            "id": ann_id,
            "image_id": img_id,
            "category_id": cat,
            "bbox": [x, y, w, h],
            "area": w * h,
            "iscrowd": 0
        })

        ann_id += 1

with open("sample_traffic/annotations.json", "w") as f:
    json.dump(coco_data, f, indent=2)

print("Dataset created successfully!")

print("Images:", len(coco_data["images"]))
print("Annotations:", len(coco_data["annotations"]))
print("Classes:", classes)

cat_id_to_name = {
    c["id"]: c["name"]
    for c in coco_data["categories"]
}

cat_counts = {
    name: 0
    for name in cat_id_to_name.values()
}

areas = []
widths = []
heights = []

for ann in coco_data["annotations"]:

    cat_name = cat_id_to_name[ann["category_id"]]

    cat_counts[cat_name] += 1

    areas.append(ann["area"])

    widths.append(ann["bbox"][2])

    heights.append(ann["bbox"][3])


fig, axes = plt.subplots(1, 3, figsize=(18, 5))

fig.suptitle(
    "Indian Traffic COCO Dataset Exploration",
    fontsize=16
)

# Graph 1: Class Distribution
axes[0].bar(
    cat_counts.keys(),
    cat_counts.values()
)

axes[0].set_title("Class Distribution")
axes[0].set_ylabel("Number of Instances")
axes[0].tick_params(axis='x', rotation=45)


# Graph 2: Bounding Box Area
axes[1].hist(areas, bins=20)

axes[1].set_title("Bounding Box Area")
axes[1].set_xlabel("Area")
axes[1].set_ylabel("Frequency")


# Graph 3: Width vs Height
axes[2].scatter(widths, heights)

axes[2].set_title("Bounding Box Width vs Height")
axes[2].set_xlabel("Width")
axes[2].set_ylabel("Height")

plt.tight_layout()
plt.show()

print("Upload an image for object detection")

uploaded = files.upload()

if not uploaded:
    print("No image uploaded")
else:
    filename = list(uploaded.keys())[0]

    img_bytes = uploaded[filename]

    img = Image.open(
        io.BytesIO(img_bytes)
    ).convert("RGB")

    img_np = np.array(img)

    print("Image loaded successfully:", filename)

    plt.figure(figsize=(7, 7))
    plt.imshow(img)
    plt.title("Uploaded Image")
    plt.axis("off")
    plt.show()

print("Loading YOLOv8 model...")

model = YOLO("yolov8n.pt")

print("YOLOv8 model loaded successfully!")

print("Detecting objects...")

results = model(img_np)

boxes = results[0].boxes

print("Detection completed!")

print("Number of objects detected:", len(boxes))

if len(boxes) == 0:

    print("No objects detected")

    plt.figure(figsize=(8, 8))
    plt.imshow(img)
    plt.title("No Detections")
    plt.axis("off")
    plt.show()

else:

    fig, ax = plt.subplots(1, 2, figsize=(16, 6))

    # Original Image
    ax[0].imshow(img)
    ax[0].set_title("Original Image")
    ax[0].axis("off")

    # Detected Image
    ax[1].imshow(img)
    ax[1].set_title("YOLOv8 Detections")
    ax[1].axis("off")

    colors = plt.cm.hsv(
        np.linspace(0, 1, len(model.names))
    ).tolist()

    for box in boxes:

        x1, y1, x2, y2 = box.xyxy[0].cpu().numpy()

        conf = box.conf[0].cpu().item()

        cls = int(box.cls[0].cpu().item())

        label = f"{model.names[cls]} {conf:.2f}"

        rect = patches.Rectangle(
            (x1, y1),
            x2-x1,
            y2-y1,
            linewidth=2,
            edgecolor=colors[cls],
            facecolor='none'
        )

        ax[1].add_patch(rect)

        ax[1].text(
            x1,
            y1-10,
            label,
            color='white',
            fontsize=9,
            bbox=dict(
                facecolor=colors[cls],
                alpha=0.8
            )
        )

    plt.tight_layout()
    plt.show()

    print("\nDetection Summary")

    for box in boxes:

        cls = int(box.cls[0].cpu().item())

        conf = box.conf[0].cpu().item()

        print(
            f"{model.names[cls]} - Confidence: {conf:.2f}"
        )