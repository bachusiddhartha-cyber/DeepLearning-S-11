import os
import json
import random
import io

import numpy as np
import matplotlib.pyplot as plt
import cv2

from PIL import Image
from google.colab import files

print("All libraries imported successfully!")

print("Generating a mock COCO dataset...")

os.makedirs("audit_data/images", exist_ok=True)

classes = ["car", "pedestrian", "traffic_sign"]

class_to_id = {
    name: i+1 for i, name in enumerate(classes)
}

coco_data = {
    "images": [],
    "annotations": [],
    "categories": [
        {"id": cid, "name": name}
        for name, cid in class_to_id.items()
    ]
}

ann_id = 1

for img_id in range(1, 31):

    base_brightness = random.choice([30, 120, 240])

    img = np.ones(
        (480, 640, 3),
        dtype=np.uint8
    ) * base_brightness

    noise = np.random.randint(
        -20, 20, (480, 640, 3),
        dtype=np.int16
    )

    img_int = img.astype(np.int16) + noise

    img = np.clip(
        img_int, 0, 255
    ).astype(np.uint8)

    img_path = f"audit_data/images/img_{img_id:03d}.jpg"

    Image.fromarray(img).save(img_path)

    coco_data["images"].append({
        "id": img_id,
        "file_name": f"img_{img_id:03d}.jpg",
        "width": 640,
        "height": 480
    })

    for _ in range(random.randint(1, 4)):

        cat = random.choice(
            list(class_to_id.values())
        )

        w = random.randint(20, 200)
        h = random.randint(20, 200)

        if img_id % 7 == 0:
            x, y = -10, -10

        elif img_id % 11 == 0:
            x, y = 620, 460

        else:
            x = random.randint(0, 640 - w)
            y = random.randint(0, 480 - h)

        coco_data["annotations"].append({
            "id": ann_id,
            "image_id": img_id,
            "category_id": cat,
            "bbox": [x, y, w, h],
            "area": w * h
        })

        ann_id += 1

with open("audit_data/annotations.json", "w") as f:
    json.dump(coco_data, f)

print("Mock dataset created successfully!")
print("Total images:", len(coco_data["images"]))
print("Total annotations:", len(coco_data["annotations"]))
print("Classes:", classes)

print("Upload an image for quality audit")

uploaded = files.upload()

if not uploaded:
    print("No image uploaded.")

else:
    filename = list(uploaded.keys())[0]

    img_bytes = uploaded[filename]

    user_img = Image.open(
        io.BytesIO(img_bytes)
    ).convert("RGB")

    user_img_np = np.array(user_img)

    # Convert image to grayscale
    gray = cv2.cvtColor(
        user_img_np,
        cv2.COLOR_RGB2GRAY
    )

    # Calculate brightness and contrast
    user_brightness = np.mean(gray)

    user_contrast = np.std(gray)

    status, color = "Good Quality", "green"

    if user_brightness < 50:
        status, color = "Too Dark", "red"

    elif user_brightness > 200:
        status, color = "Too Bright", "orange"

    elif user_contrast < 20:
        status, color = "Low Contrast (Blurry)", "orange"

    print("Image:", filename)
    print("Brightness:", round(user_brightness, 2), "/ 255")
    print("Contrast:", round(user_contrast, 2))
    print("Verdict:", status)

    plt.figure(figsize=(7, 7))
    plt.imshow(user_img)
    plt.title("Uploaded Image")
    plt.axis("off")
    plt.show()

print("Running Dataset Audit...")

img_metadata = {
    img["id"]: img
    for img in coco_data["images"]
}

cat_id_to_name = {
    c["id"]: c["name"]
    for c in coco_data["categories"]
}

class_counts = {
    name: 0
    for name in class_to_id.keys()
}

brightness_scores = []
contrast_scores = []

invalid_boxes = []
valid_boxes = []

for ann in coco_data["annotations"]:

    class_counts[
        cat_id_to_name[ann["category_id"]]
    ] += 1

    img_w = img_metadata[ann["image_id"]]["width"]

    img_h = img_metadata[ann["image_id"]]["height"]

    x, y, w, h = ann["bbox"]

    if (
        x < 0 or y < 0
        or (x + w) > img_w
        or (y + h) > img_h
        or w <= 0 or h <= 0
    ):

        invalid_boxes.append(ann)

    else:
        valid_boxes.append(ann)


for img in coco_data["images"]:

    img_path = (
        f"audit_data/images/{img['file_name']}"
    )

    loaded_img = cv2.imread(img_path)

    gray = cv2.cvtColor(
        loaded_img,
        cv2.COLOR_BGR2GRAY
    )

    brightness_scores.append(np.mean(gray))

    contrast_scores.append(np.std(gray))


print("Total Annotations:", len(coco_data["annotations"]))

print("Valid Boxes:", len(valid_boxes))

print("Invalid Boxes:", len(invalid_boxes))

print("Dataset audit completed!")

