import torch

print("PyTorch Version:", torch.__version__)
print("CUDA Available:", torch.cuda.is_available())

if torch.cuda.is_available():
    print("GPU Name:", torch.cuda.get_device_name(0))
    device = torch.device("cuda")
else:
    print("GPU not available. Using CPU.")
    device = torch.device("cpu")

import torch
from torchvision import models, transforms
from PIL import Image

# Load pretrained MobileNetV3 model
weights = models.MobileNet_V3_Small_Weights.DEFAULT

model = models.mobilenet_v3_small(weights=weights)

# Move model to GPU
model = model.to(device)

# Set evaluation mode
model.eval()

# Image preprocessing
preprocess = weights.transforms()

# ImageNet class names
categories = weights.meta["categories"]

print("Model loaded successfully!")
print("Model: MobileNetV3 Small")
print("Device:", device)
print("Number of classes:", len(categories))

from fastapi import FastAPI, File, UploadFile
from fastapi.responses import JSONResponse
import io
import time

app = FastAPI(title="VisionPort AI Inference API")

@app.get("/")
def home():
    return {
        "project": "VisionPort",
        "message": "AI Vision Inference System Running"
    }

@app.get("/health")
def health():
    return {
        "status": "healthy",
        "model": "MobileNetV3 Small",
        "device": str(device)
    }

@app.post("/predict")
async def predict(file: UploadFile = File(...)):

    start_time = time.time()

    # Read uploaded image
    image_bytes = await file.read()
    image = Image.open(io.BytesIO(image_bytes)).convert("RGB")

    # Preprocess image
    input_tensor = preprocess(image).unsqueeze(0).to(device)

    # GPU model inference
    with torch.inference_mode():
        output = model(input_tensor)

        probabilities = torch.nn.functional.softmax(
            output[0], dim=0
        )

        top_probabilities, top_indices = torch.topk(
            probabilities, 5
        )

    # Prepare predictions
    predictions = []

    for probability, index in zip(
        top_probabilities.tolist(),
        top_indices.tolist()
    ):
        predictions.append({
            "class": categories[index],
            "confidence": round(probability * 100, 2)
        })

    inference_time = round(
        (time.time() - start_time) * 1000, 2
    )

    return {
        "filename": file.filename,
        "predictions": predictions,
        "inference_time_ms": inference_time,
        "device": str(device)
    }

